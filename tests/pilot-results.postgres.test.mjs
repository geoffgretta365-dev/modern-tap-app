import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { createRequire } from 'node:module';
const tools = process.env.MODERNTAP_PG_TOOLS;
for(const existingIndex of [false,true]) test('clean tap migration, concurrent repeats, token protection (existing index '+existingIndex+')',{skip:!tools,timeout:60000},async()=>{
  const requireTools = createRequire(path.join(tools, 'package.json'));
  const { default: EmbeddedPostgres } = await import(requireTools.resolve('embedded-postgres'));
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'moderntap-pilot-db-'));
  const socket = net.createServer(); await new Promise(r => socket.listen(0, '127.0.0.1', r));
  const port = socket.address().port; await new Promise(r => socket.close(r));
  const pg = new EmbeddedPostgres({ databaseDir: path.join(temp, 'data'), user: 'postgres', password: 'local-fixture', port, persistent: false, onLog() {}, onError() {}, initdbFlags: ['--locale=C', '--encoding=UTF8'], postgresFlags: ['-h', '127.0.0.1'] });
  let db;
  const connections = [];
  try {
    await pg.initialise(); await pg.start(); db = pg.getPgClient(); await db.connect();
    // Table shapes follow the read-only PostgREST schema inspection. Policies below
    // deliberately include a permissive policy to verify the new restrictive boundary.
    await db.query(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth;
      create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      create function auth.role() returns text language sql as $$ select nullif(current_setting('request.jwt.claim.role',true),'') $$;
      grant usage on schema public,auth to anon,authenticated,service_role;
      grant execute on all functions in schema auth to anon,authenticated,service_role;
      create table businesses(id uuid primary key default gen_random_uuid(), owner_id uuid not null, name text not null, created_at timestamptz not null default now());
      create table plaques(id uuid primary key default gen_random_uuid(), business_id uuid not null references businesses(id), name text not null, code text not null unique, destination_url text not null, active boolean not null default true, created_at timestamptz not null default now(), mode text not null default 'direct_link', purpose text not null default 'general');
      create table tap_events(id bigint generated by default as identity primary key, plaque_id uuid not null references plaques(id), user_agent text, created_at timestamptz not null default now());
      create table subscriptions(id uuid primary key default gen_random_uuid(), business_id uuid not null unique references businesses(id), status text not null default 'inactive', stripe_subscription_id text, stripe_customer_id text, stripe_price_id text);
      grant all on businesses,plaques,subscriptions to authenticated,service_role;
      grant select on businesses to anon;
      alter table businesses enable row level security;
      create policy fixture_owner on businesses for all to authenticated using(owner_id=auth.uid()) with check(owner_id=auth.uid());
      create policy fixture_permissive on businesses for select to anon,authenticated using(true);
    `);
    await db.query(fs.readFileSync('supabase/migrations/20260929_add_admin_pilots.sql', 'utf8'));
    await db.query('grant all on tap_events to authenticated,service_role; grant usage on all sequences in schema public to authenticated,service_role');
    const owner='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
    const business=(await db.query("insert into businesses(name,is_pilot,owner_id,trial_started_at,trial_ends_at) values('Pilot',true,$1,'2026-10-20T00:00:00Z','2026-11-19T00:00:00Z') returning id",[owner])).rows[0].id;
    const p=(await db.query("insert into plaques(business_id,name,code,destination_url) values($1,'Table','CODE','https://example.test') returning id",[business])).rows[0].id;
    const second=(await db.query("insert into plaques(business_id,name,code,destination_url) values($1,'Checkbook','CODE2','https://example.test') returning id",[business])).rows[0].id;
    if(existingIndex)await db.query('create index existing_tap_time on tap_events(plaque_id,created_at desc)');
    for(const [plaque,ua,time]of [[p,'Human','2026-01-01T00:00:00Z'],[p,'Human','2026-01-01T00:00:29Z'],[p,'Human','2026-01-01T00:00:59Z'],[p,'Different','2026-01-01T00:00:59Z'],[second,'Human','2026-01-01T00:00:59Z']])await db.query('insert into tap_events(plaque_id,user_agent,created_at) values($1,$2,$3)',[plaque,ua,time]);
    const markers=['facebookexternalhit','Facebot','Twitterbot','Slackbot','LinkedInBot','WhatsApp','TelegramBot','Discordbot','Googlebot','bingbot','crawler','spider','bot/'];
    for(const marker of markers)await db.query("insert into tap_events(plaque_id,user_agent,created_at) values($1,$2,'2026-01-02')",[p,'Mozilla '+marker.toUpperCase()]);
    await db.query(fs.readFileSync('supabase/migrations/20260930_add_pilot_results.sql','utf8'));
    const old=(await db.query('select is_bot,is_repeat from tap_events order by id')).rows;
    assert.deepEqual(old.slice(0,5).map(x=>x.is_repeat),[false,true,true,false,false]);
    assert.ok(old.slice(5).every(x=>x.is_bot));
    const corrected=(await db.query('select trial_started_at,trial_ends_at from businesses where id=$1',[business])).rows[0];
    assert.equal(corrected.trial_started_at.toISOString(),'2026-10-20T04:00:00.000Z');
    assert.equal(corrected.trial_ends_at.toISOString(),'2026-11-19T05:00:00.000Z');
    assert.equal((await db.query("select count(*)::int n from pg_indexes where tablename='tap_events' and indexdef like '%plaque_id, created_at%'")).rows[0].n,1);
    async function session(role,uid=''){
      const c=pg.getPgClient();await c.connect();connections.push(c);await c.query(`set role ${role}`);
      await c.query("select set_config('request.jwt.claim.role',$1,false),set_config('request.jwt.claim.sub',$2,false)",[role,uid]);return c;
    }
    const a=await session('service_role'), b=await session('service_role');
    const insert=(client,ua,plaque=p,bot=false)=>client.query('insert into tap_events(plaque_id,user_agent,is_bot) values($1,$2,$3) returning id,is_repeat,is_bot,created_at',[plaque,ua,bot]);
    assert.equal((await insert(a,'Phone')).rows[0].is_repeat,false);
    assert.equal((await insert(a,'Phone')).rows[0].is_repeat,true);
    assert.equal((await insert(a,'Phone',second)).rows[0].is_repeat,false);
    assert.equal((await insert(a,'phone')).rows[0].is_repeat,false);
    assert.equal((await insert(a,null)).rows[0].is_repeat,false);
    assert.equal((await insert(a,null)).rows[0].is_repeat,true);
    assert.equal((await insert(a,'HEAD phone',p,true)).rows[0].is_bot,true);
    await db.query("update tap_events set created_at=clock_timestamp()-interval '31 seconds' where user_agent='Phone' and plaque_id=$1",[p]);
    assert.equal((await insert(a,'Phone')).rows[0].is_repeat,false);
    await db.query("update tap_events set created_at=clock_timestamp()-interval '29 seconds' where user_agent='Phone' and plaque_id=$1",[p]);
    assert.equal((await insert(a,'Phone')).rows[0].is_repeat,true);
    // Two HTTP requests can reach separate DB connections simultaneously.
    await a.query('begin');const first=await insert(a,'Concurrent');assert.equal(first.rows[0].is_repeat,false);
    let finished=false;const racing=insert(b,'Concurrent').finally(()=>{finished=true;});
    await new Promise(r=>setTimeout(r,100));assert.equal(finished,false);await a.query('commit');
    assert.equal((await racing).rows[0].is_repeat,true);
    assert.equal((await db.query("select count(*)::int n from tap_events where user_agent='Concurrent' and not is_bot and not is_repeat")).rows[0].n,1);
    // Browser owners cannot set or revoke tokens through direct PostgREST access.
    const customer=await session('authenticated',owner);
    await assert.rejects(customer.query("update businesses set pilot_share_token='spoof' where id=$1",[business]),/administrator/);
    await a.query('update businesses set pilot_share_token=$1 where id=$2',['A'.repeat(43),business]);
    await assert.rejects(customer.query('update businesses set pilot_share_token=null where id=$1',[business]),/administrator/);
    await assert.rejects(customer.query("insert into businesses(name,owner_id,pilot_share_token) values('Spoof',$1,'spoof')",[owner]),/administrator/);
    await customer.query("update businesses set name='Allowed name update' where id=$1",[business]);
    await assert.rejects(a.query("insert into businesses(name,is_pilot,pilot_share_token) values('Duplicate',true,$1)",['A'.repeat(43)]),/unique constraint/);
    await a.query('update businesses set pilot_share_token=null where id=$1',[business]);
    assert.equal((await db.query('select id from businesses where pilot_share_token=$1',['A'.repeat(43)])).rowCount,0);
  } finally {
    for (const c of connections) await c.end();
    if (db) await db.end();
    await pg.stop().catch(() => {}); fs.rmSync(temp, { recursive: true, force: true });
  }
});
